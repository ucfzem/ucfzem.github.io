def main():
    stories = []
    n = 0
    for cat, titles in BOOK:
        for t in titles:
            n += 1
            stories.append({
                "id": n,
                "number": n,
                "category": cat,
                "title": t,
                "content": PLACEHOLDER,
            })

    data = {
        "bookInfo": {
            "title": "صحيح القصص النبوي",
            "author": "د. عمر سليمان الأشقر",
            "totalStories": n,
            "language": "ar",
            "direction": "rtl",
            "note": ("هيكل العناوين والأبواب (5 أبواب). النص الكامل لكل قصة "
                     "يُستخرج من نسختك الخاصة من الكتاب عبر tools/extract."),
        },
        "stories": stories,
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    cats = len(BOOK)
    print(f"✅ Generated {n} stories across {cats} أبواب -> {OUT}")


if __name__ == "__main__":
    main()
